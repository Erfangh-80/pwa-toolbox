"use client";

import { useEffect, useState } from "react";

import { useOnlineStatus } from "@/lib/useOnlineStatus";
import { useSupport } from "@/lib/useSupport";

import { Button } from "./ui/Button";
import { Card } from "./ui/Card";
import { DataList } from "./ui/DataList";
import { Notice } from "./ui/Notice";

type ServiceWorkerInfo = {
  supported: boolean;
  registered: boolean;
  scope: string | null;
};

const formatBytes = (bytes: number): string => {
  if (!Number.isFinite(bytes) || bytes <= 0) {
    return "0 B";
  }
  const units = ["B", "KB", "MB", "GB"];
  const exponent = Math.min(Math.floor(Math.log(bytes) / Math.log(1024)), units.length - 1);
  return `${(bytes / 1024 ** exponent).toFixed(exponent === 0 ? 0 : 1)} ${units[exponent]}`;
};

const readServiceWorkerInfo = async (): Promise<ServiceWorkerInfo> => {
  if (!("serviceWorker" in navigator)) {
    return { supported: false, registered: false, scope: null };
  }

  try {
    const registration = await navigator.serviceWorker.getRegistration();
    return {
      supported: true,
      registered: Boolean(registration),
      scope: registration?.scope ?? null,
    };
  } catch {
    return { supported: true, registered: false, scope: null };
  }
};

const readCacheNames = async (): Promise<string[]> => {
  if (!("caches" in window)) {
    return [];
  }

  try {
    return await caches.keys();
  } catch {
    return [];
  }
};

const readStorageUsage = async (): Promise<string> => {
  try {
    if (!navigator.storage?.estimate) {
      return "unavailable";
    }
    const { usage = 0, quota = 0 } = await navigator.storage.estimate();
    return `${formatBytes(usage)} of ${formatBytes(quota)}`;
  } catch {
    return "unavailable";
  }
};

export const OfflineCard = () => {
  const support = useSupport(() => "onLine" in navigator);
  const online = useOnlineStatus();
  const [serviceWorker, setServiceWorker] = useState<ServiceWorkerInfo | null>(null);
  const [cacheNames, setCacheNames] = useState<string[]>([]);
  const [storageUsage, setStorageUsage] = useState("unknown");
  const [reloadToken, setReloadToken] = useState(0);

  useEffect(() => {
    let cancelled = false;

    void (async () => {
      const info = await readServiceWorkerInfo();
      const names = await readCacheNames();
      const usage = await readStorageUsage();

      if (cancelled) {
        return;
      }

      setServiceWorker(info);
      setCacheNames(names);
      setStorageUsage(usage);
    })();

    return () => {
      cancelled = true;
    };
  }, [reloadToken]);

  return (
    <Card
      index={2}
      title="Offline support"
      api="navigator.onLine"
      icon="offline"
      support={support}
      description="Track connectivity in real time and inspect what the service worker has actually cached for offline use."
      footnote="Fetch strategies are generated by Serwist at build time; this card only reports what is live."
    >
      <div className="flex items-center gap-2 rounded-lg border border-line bg-surface-raised px-3 py-2">
        <span
          className={`size-2 rounded-full ${online ? "bg-accent" : online === false ? "bg-warn" : "bg-muted"}`}
          aria-hidden="true"
        />
        <span className="font-mono text-xs uppercase tracking-[0.14em] text-ink">
          {online === null ? "Detecting…" : online ? "Online" : "Offline"}
        </span>
        <span className="ml-auto font-mono text-[11px] text-muted">
          navigator.onLine: {online === null ? "…" : String(online)}
        </span>
      </div>

      <DataList
        items={[
          {
            label: "Service worker",
            value:
              serviceWorker === null
                ? "checking…"
                : serviceWorker.registered
                  ? "registered"
                  : serviceWorker.supported
                    ? "not registered"
                    : "unsupported",
          },
          {
            label: "Active caches",
            value: cacheNames.length ? `${cacheNames.length} · ${cacheNames.join(", ")}` : "none",
          },
          { label: "Storage", value: storageUsage },
        ]}
      />

      {online === false ? (
        <Notice tone="warn" announce>
          Offline. Pages already cached by the service worker keep working; uncached
          routes will fail until the connection returns.
        </Notice>
      ) : null}

      {serviceWorker?.supported && !serviceWorker.registered ? (
        <Notice>
          No service worker is registered in this environment, so nothing is cached yet.
        </Notice>
      ) : null}

      <div className="mt-auto flex flex-wrap gap-2 pt-1">
        <Button variant="secondary" onClick={() => setReloadToken((token) => token + 1)}>
          Refresh status
        </Button>
        <Button
          variant="primary"
          onClick={() => window.location.reload()}
          disabled={online === null}
        >
          Reload page
        </Button>
      </div>
    </Card>
  );
};
